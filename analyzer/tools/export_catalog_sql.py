"""Generates supabase/rule_engine.sql from the analyzer's rule catalog and product taxonomy.

    python tools/export_catalog_sql.py            # writes ../supabase/rule_engine.sql

app/rules/lm_rules.csv and app/rules/categories.json are the single source of truth; the SQL file
stores the same catalog in Supabase (public.product_categories, public.compliance_rules) together
with the selector function and the category x rule matrix the app and dashboards query.
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))

from app.rules.catalog import load_taxonomy  # noqa: E402
from app.rules.engine import load_rules  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "supabase", "rule_engine.sql")


def q(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def arr(items) -> str:
    items = list(items)
    if not items:
        return "'{}'::text[]"
    return "array[" + ", ".join(q(i) for i in items) + "]::text[]"


def js(v) -> str:
    return "null" if v in (None, {}, []) else q(json.dumps(v, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"


HEADER = """-- ComplyVision: category-aware Legal Metrology rule engine catalog.
--
-- GENERATED by analyzer/tools/export_catalog_sql.py from analyzer/app/rules/lm_rules.csv and
-- analyzer/app/rules/categories.json - edit those files and re-generate; do not edit by hand.
--
-- Run in the Supabase SQL editor AFTER schema.sql, authority_module.sql and inspector_module.sql.
-- Safe to re-run: every statement is an upsert or `if not exists`.
--
-- What this adds
--   * public.product_categories   - {n_cat} product categories with their governing laws, quantity measure
--                                   (Rule 12(2) / Fourth Schedule), BIS standards and the tags rules select on
--   * public.package_types        - retail / wholesale / institutional / export (Rules 2(k), 2(r), 3(c), 25)
--   * public.compliance_rules     - extended to {n_rules} rules with section, scope, selector, validator and params
--   * public._rule_applies()      - evaluates a rule's `applies_to` selector against a category
--   * public.category_rule_matrix - which rules govern which category (view)
--   * public.inspector_categories - token-protected RPC: the taxonomy + per-category rule list for the app
--
-- Legal basis: LM (Packaged Commodities) Rules, 2011 as amended by G.S.R. 858(E) 2016, 629(E) 2017 (+ corrigendum
-- 1373(E)), 779(E) 2021, 226(E) / 577(E) / 648(E) 2022, 456(E) / 722(E) 2023, 778(E) / 881(E) 2025 and 128(E) /
-- 312(E) / 418(E) / Fourth Amendment of 21.09.2026; plus the FSS Act 2006 regulations, COTPA 2003, Drugs and
-- Cosmetics Rules 1945, Cosmetics Rules 2020, Medical Devices Rules 2017, Insecticides Rules 1971, FCO 1985,
-- Seeds Act 1966 and BIS Quality Control Orders named per rule / category. Catalog version {version}.
"""

DDL = """
-- ===========================================================================
-- 1. Taxonomy tables
-- ===========================================================================
create table if not exists public.product_categories (
  id                text primary key,
  sort_order        integer not null,
  name              text not null,
  group_id          text not null,
  group_name        text not null,
  tags              text[] not null default '{}',
  laws              text[] not null default '{}',
  quantity_dims     text[] not null default '{}',
  quantity_ref      text,
  volume_needs_mass boolean not null default false,
  standards         jsonb,
  keywords          jsonb not null default '{}'::jsonb,
  legacy_names      text[] not null default '{}',
  catalog_version   text not null,
  updated_at        timestamptz not null default now()
);

create table if not exists public.package_types (
  id        text primary key,
  name      text not null,
  reference text,
  markers   text[] not null default '{}'
);

alter table public.compliance_rules add column if not exists section         text;
alter table public.compliance_rules add column if not exists scope           text not null default 'retail';
alter table public.compliance_rules add column if not exists applies_to      text[] not null default '{all}';
alter table public.compliance_rules add column if not exists validator       text;
alter table public.compliance_rules add column if not exists params          jsonb;
alter table public.compliance_rules add column if not exists catalog_version text;
alter table public.compliance_rules add column if not exists active          boolean not null default true;
alter table public.compliance_rules add column if not exists updated_at      timestamptz not null default now();
do $c$ begin
  alter table public.compliance_rules add constraint compliance_rules_scope_chk check (scope in ('retail', 'wholesale', 'always'));
exception when duplicate_object then null;
end $c$;

alter table public.product_categories enable row level security;
alter table public.package_types      enable row level security;
revoke all on public.product_categories, public.package_types from anon, authenticated;

-- ===========================================================================
-- 2. Selector: does a rule's applies_to list select this category?
--    'all' | 'tag:<tag>' | 'cat:<id>' | 'group:<group>'; a leading '-' excludes.
-- ===========================================================================
create or replace function public._selector_matches(p_sel text, c public.product_categories)
returns boolean
language sql
immutable
as $$
  select case
    when p_sel = 'all' then true
    when p_sel like 'tag:%'   then substr(p_sel, 5) = any (c.tags)
    when p_sel like 'cat:%'   then substr(p_sel, 5) = c.id
    when p_sel like 'group:%' then substr(p_sel, 7) = c.group_id
    else false
  end;
$$;

create or replace function public._rule_applies(p_applies text[], c public.product_categories)
returns boolean
language sql
immutable
as $$
  select not exists (select 1 from unnest(p_applies) s where s like '-%' and public._selector_matches(substr(s, 2), c))
     and (not exists (select 1 from unnest(p_applies) s where s not like '-%')
          or exists (select 1 from unnest(p_applies) s where s not like '-%' and public._selector_matches(s, c)));
$$;
revoke all on function public._selector_matches(text, public.product_categories) from public, anon, authenticated;
revoke all on function public._rule_applies(text[], public.product_categories) from public, anon, authenticated;
"""

TAIL = """
-- Rules no longer in the catalog stay for historical scans but are switched off
update public.compliance_rules set active = false where catalog_version is distinct from {version};

-- ===========================================================================
-- 5. Category x rule matrix
-- ===========================================================================
create or replace view public.category_rule_matrix as
  select c.id as category_id, c.name as category_name, c.group_name, r.id as rule_id, r.title, r.section,
         r.scope, r.severity, r.reference, r.sort_order
    from public.product_categories c
    join public.compliance_rules r on r.active and public._rule_applies(r.applies_to, c);
revoke all on public.category_rule_matrix from anon, authenticated;

-- ===========================================================================
-- 6. inspector_categories: the taxonomy for the category picker, and the rule list of one category
-- ===========================================================================
create or replace function public.inspector_categories(p_token uuid, p_category text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare
  v_me   uuid;
  v_dash text;
begin
  select s.officer_uuid, s.dashboard into v_me, v_dash from public._session_officer(p_token) s;
  if v_me is null then return jsonb_build_object('ok', false, 'code', 'session_expired'); end if;
  if v_dash not in ('INSPECTOR', 'AUTHORITY') then return jsonb_build_object('ok', false, 'code', 'forbidden'); end if;

  return jsonb_build_object(
    'ok', true,
    'version', (select max(catalog_version) from public.product_categories),
    'categories', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', c.id, 'name', c.name, 'group', c.group_id, 'group_name', c.group_name,
               'laws', to_jsonb(c.laws), 'tags', to_jsonb(c.tags),
               'quantity', jsonb_build_object('dims', to_jsonb(c.quantity_dims), 'ref', c.quantity_ref),
               'standards', c.standards,
               'rules', (select count(*) from public.compliance_rules r
                          where r.active and r.scope <> 'wholesale' and public._rule_applies(r.applies_to, c))
             ) order by c.sort_order)
      from public.product_categories c
    ), '[]'::jsonb),
    'package_types', coalesce((
      select jsonb_agg(jsonb_build_object('id', p.id, 'name', p.name, 'ref', p.reference) order by p.id)
      from public.package_types p
    ), '[]'::jsonb),
    'rules', case when p_category is null then '[]'::jsonb else coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', r.id, 'title', r.title, 'section', r.section, 'reference', r.reference,
               'severity', r.severity, 'scope', r.scope, 'description', r.description
             ) order by r.sort_order)
      from public.compliance_rules r, public.product_categories c
      where c.id = p_category and r.active and r.scope <> 'wholesale' and public._rule_applies(r.applies_to, c)
    ), '[]'::jsonb) end
  );
end;
$$;
revoke all on function public.inspector_categories(uuid, text) from public;
grant execute on function public.inspector_categories(uuid, text) to anon, authenticated;
"""


def main() -> None:
    tax = load_taxonomy()
    rules = load_rules()
    with open(os.path.join(HERE, "..", "app", "rules", "categories.json"), encoding="utf-8") as fh:
        raw = {c["id"]: c for c in json.load(fh)["categories"]}
    version = tax.version
    parts = [HEADER.format(n_cat=len(tax.categories), n_rules=len(rules), version=version), DDL]

    parts.append("""
-- ===========================================================================
-- 3. Product categories
-- ===========================================================================
insert into public.product_categories
  (id, sort_order, name, group_id, group_name, tags, laws, quantity_dims, quantity_ref, volume_needs_mass, standards,
   keywords, legacy_names, catalog_version, updated_at)
values""")
    rows = []
    for i, c in enumerate(tax.categories, start=1):
        rc = raw[c.id]
        rows.append(f"  ({q(c.id)}, {i * 10}, {q(c.name)}, {q(c.group)}, {q(tax.groups.get(c.group, c.group))},\n"
                    f"   {arr(sorted(c.tags))},\n   {arr(c.laws)},\n"
                    f"   {arr(c.dims)}, {q(c.quantity_ref)}, {q(c.volume_needs_mass)}, {js(c.standards)},\n"
                    f"   {js(rc.get('keywords') or {})}, {arr(rc.get('legacy') or [])}, {q(version)}, now())")
    parts.append(",\n".join(rows))
    parts.append("""on conflict (id) do update set
  sort_order = excluded.sort_order, name = excluded.name, group_id = excluded.group_id, group_name = excluded.group_name,
  tags = excluded.tags, laws = excluded.laws, quantity_dims = excluded.quantity_dims, quantity_ref = excluded.quantity_ref,
  volume_needs_mass = excluded.volume_needs_mass, standards = excluded.standards, keywords = excluded.keywords,
  legacy_names = excluded.legacy_names, catalog_version = excluded.catalog_version, updated_at = now();
""")

    parts.append("insert into public.package_types (id, name, reference, markers) values")
    parts.append(",\n".join(f"  ({q(p['id'])}, {q(p['name'])}, {q(p.get('ref'))}, {arr(p.get('markers') or [])})" for p in tax.package_types))
    parts.append("on conflict (id) do update set name = excluded.name, reference = excluded.reference, markers = excluded.markers;\n")

    parts.append("""
-- ===========================================================================
-- 4. Rule catalog (category = rule section, kept for the existing RPCs and app)
-- ===========================================================================
insert into public.compliance_rules
  (id, sort_order, title, reference, category, section, severity, description, scope, applies_to, validator, params,
   catalog_version, active, updated_at)
values""")
    parts.append(",\n".join(
        f"  ({q(r.id)}, {r.sort_order}, {q(r.title)},\n   {q(r.reference)},\n   {q(r.section)}, {q(r.section)}, {q(r.severity)},\n"
        f"   {q(r.description)},\n   {q(r.scope)}, {arr(r.applies_to)}, {q(r.validator)}, {js(r.params)}, {q(version)}, true, now())"
        for r in rules))
    parts.append("""on conflict (id) do update set
  sort_order = excluded.sort_order, title = excluded.title, reference = excluded.reference, category = excluded.category,
  section = excluded.section, severity = excluded.severity, description = excluded.description, scope = excluded.scope,
  applies_to = excluded.applies_to, validator = excluded.validator, params = excluded.params,
  catalog_version = excluded.catalog_version, active = true, updated_at = now();
""")
    parts.append(TAIL.format(version=q(version)))

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))
    print(f"wrote {os.path.relpath(OUT)}: {len(tax.categories)} categories, {len(rules)} rules")


if __name__ == "__main__":
    main()
